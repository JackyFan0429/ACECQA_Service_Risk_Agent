"""Small local BM25 retrieval index for curated ACECQA policy/guidance chunks.

The policy corpus is generated by scripts/ingest_policy.py from official ACECQA pages.
No LLM performs retrieval scoring; search_policy therefore remains inspectable and repeatable.
"""

from __future__ import annotations

import json
import math
import os
import re
from collections import Counter
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Iterable

from acecqa_agent.config import PROJECT_ROOT

TOKEN_RE = re.compile(r"[a-z0-9]+(?:'[a-z0-9]+)?")
STOPWORDS = {
    "a", "an", "and", "are", "as", "at", "be", "before", "by", "can", "do", "does",
    "for", "from", "how", "i", "if", "in", "into", "is", "it", "of", "on", "or",
    "should", "that", "the", "their", "this", "to", "what", "when", "which", "with",
}


class PolicyCorpusMissingError(RuntimeError):
    pass


def _default_corpus_path() -> Path:
    override = os.getenv("ACECQA_POLICY_CORPUS_PATH")
    if override:
        return Path(override).expanduser().resolve()
    # Use the same project-root contract as the rest of the application.
    # In Docker/non-editable installs, __file__ lives under site-packages, while
    # ACECQA_PROJECT_ROOT points at the copied application root (normally /app).
    return PROJECT_ROOT / "data" / "policy" / "policy_chunks.jsonl"


def _tokens(text: str) -> list[str]:
    return [token for token in TOKEN_RE.findall(text.lower()) if token not in STOPWORDS]


@dataclass(frozen=True)
class IndexedChunk:
    raw: dict
    tokens: list[str]
    counts: Counter[str]


class PolicyRepository:
    def __init__(self, corpus_path: Path | str | None = None) -> None:
        self.corpus_path = Path(corpus_path) if corpus_path is not None else _default_corpus_path()
        if not self.corpus_path.exists():
            raise PolicyCorpusMissingError(
                f"Policy corpus not found at {self.corpus_path}. "
                "Run: python scripts/ingest_policy.py"
            )

        chunks: list[dict] = []
        with self.corpus_path.open("r", encoding="utf-8") as handle:
            for line_no, line in enumerate(handle, start=1):
                stripped = line.strip()
                if not stripped:
                    continue
                try:
                    item = json.loads(stripped)
                except json.JSONDecodeError as exc:
                    raise ValueError(f"Invalid JSONL at line {line_no}: {self.corpus_path}") from exc
                chunks.append(item)

        if not chunks:
            raise PolicyCorpusMissingError(f"Policy corpus is empty: {self.corpus_path}")

        self._chunks = chunks
        self._indexed: list[IndexedChunk] = []
        self._doc_freq: Counter[str] = Counter()
        total_len = 0

        for chunk in chunks:
            weighted = " ".join(
                [
                    str(chunk.get("source_title", "")),
                    str(chunk.get("source_title", "")),
                    str(chunk.get("section", "")),
                    str(chunk.get("section", "")),
                    " ".join(chunk.get("topics", []) or []),
                    " ".join(chunk.get("keywords", []) or []),
                    str(chunk.get("text", "")),
                ]
            )
            toks = _tokens(weighted)
            counts = Counter(toks)
            self._indexed.append(IndexedChunk(raw=chunk, tokens=toks, counts=counts))
            total_len += len(toks)
            for term in counts:
                self._doc_freq[term] += 1

        self._avg_len = total_len / max(len(self._indexed), 1)

    @property
    def chunk_count(self) -> int:
        return len(self._chunks)

    def _bm25(self, query_terms: Iterable[str], doc: IndexedChunk) -> float:
        k1 = 1.5
        b = 0.75
        n_docs = len(self._indexed)
        doc_len = max(len(doc.tokens), 1)
        score = 0.0
        for term in query_terms:
            tf = doc.counts.get(term, 0)
            if tf == 0:
                continue
            df = self._doc_freq.get(term, 0)
            idf = math.log(1 + (n_docs - df + 0.5) / (df + 0.5))
            denom = tf + k1 * (1 - b + b * doc_len / max(self._avg_len, 1.0))
            score += idf * ((tf * (k1 + 1)) / denom)
        return score

    def search(self, query: str, *, top_k: int = 5, topic: str | None = None) -> list[dict]:
        terms = _tokens(query)
        if not terms:
            return []

        candidates: list[tuple[float, dict]] = []
        for doc in self._indexed:
            raw = doc.raw
            topics = raw.get("topics", []) or []
            if topic and topic not in topics:
                continue
            score = self._bm25(terms, doc)
            if score <= 0:
                continue
            candidates.append((score, raw))

        candidates.sort(key=lambda pair: (-pair[0], str(pair[1].get("chunk_id", ""))))
        results: list[dict] = []
        for score, raw in candidates[:top_k]:
            item = dict(raw)
            item["retrieval_score"] = round(float(score), 6)
            results.append(item)
        return results


@lru_cache(maxsize=4)
def _cached_repository(path: str) -> PolicyRepository:
    return PolicyRepository(path)


def get_policy_repository() -> PolicyRepository:
    path = str(_default_corpus_path())
    return _cached_repository(path)
